#display game rules
print("Welcome to Rock Paper Scissors!\n")
print("Winning Rules:")
print("Rock vs Paper -> Paper wins")
print("Rock vs Scissors -> Rock wins")
print("Paper vs Scissors -> Scissors wins\n")

choices = [Rock, Paper, Scissors]

import random

choices = ["Rock", "Paper", "Scissors"]

while True:
  print("Choose an option: ")
  print("1 - Rock")
  print("2 - Paper")
  print("3 - Scissors")

  try:
    choice = int(input("Enter your choice: "))
  except ValueError:
    print("Invalid input. Please enter a number.\n")
    continue

  if choice > 3 or choice < 1:
    print("Enter a valid choice (1, 2, or 3).\n")
    continue

  user_choice = choices[choice - 1]
  print("\nUser choice is:", user_choice)
  print("Now it's computer's turn...")

  comp_idx = random.randint(1, 3)
  comp_choice = choices[comp_idx - 1]
  print("Computer choice is:", comp_choice)
  print(user_choice, "vs", comp_choice)

  # Determine winner
  if user_choice == comp_choice:
    print("It's a tie!")
  elif (
    (choice == 1 and comp_idx == 3) or
    (choice == 2 and comp_idx == 1) or
    (choice == 3 and comp_idx == 2)
  ):
    print("User wins!")
  else:
    print("Computer wins!")

  # Ask to play again
  play_again = ""
  while play_again not in ['y', 'n']:
    play_again = input("\nDo you want to play again? (Y/N): ").lower()
    if play_again not in ['y', 'n']:
      print("Please enter Y or N.")

  if play_again == 'n':
    print("\nThanks for playing, goodbye!")
    break

