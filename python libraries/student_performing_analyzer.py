import numpy as np

students = np.array(["Alice", "Bob", "Charlie",
                     "Diana", "Ethan", "Fiona"])

subjects = np.array(["Math", "Python", "Statistics", "SQL"])

grades = np.array([
    [85, 90, 78, 88],
    [70, 75, 80, 72],
    [95, 92, 96, 94],
    [60, 65, 70, 68],
    [88, 84, 82, 90],
    [76, 80, 85, 79]
])


#task 1: explore the dataset

print("=" * 45)
print("Task 1: explore the dataset")
print("=" * 45)

print("\nAll grades:")
print(grades)

print("\nDataset shape (rows, columns)")
print(grades.shape)

print("\nNumber of students:", grades.shape[0])
print("Number of subjects:", grades.shape[1])

print("\nAlice's grades:")
print(grades[0])

print("\nEvery student's python grade:")
print(grades[:, 1])

print("\nGrades of the first three students:")
print(grades[:3])

#calculate statistics
print("\n" + "=" * 45)
print("task 2: calculate statistics")
print("=" * 45)

student_averages = np.mean(grades, axis=1)

print("\nStudent averages:")
for i in range(len(students)):
  print(students[i], ":", round(student_averages[i], 2))

subject_averages = np.mean(grades, axis=0)

print("\nSubject averages:")
for i in range(len(subjects)):
  print(subjects[i], ":", round(subject_averages[i], 2))

print("\nHighest grade:", np.max(grades))
print("Lowest grade:", np.min(grades))

subject_std = np.std(grades, axis=0)

print("\nStandard deviation by subject:")
for i in range(len(subjects)):
  print(subjects[i], ":", round(subject_std[i], 2))


#task 3, filter students and grades

print("\n" + "=" * 45)
print("Task 3: filter students and grades")
print("=" * 45)

#find all individual grades above 90
high_grades = grades[grades > 90]

print("\nGrades above 90:")
print(high_grades)

#students with averages of at least 85
high_performers = students[student_averages >= 85]

print("\nStudentes averaging at least 85:")
print(high_performers)
#less than 70
low_performers = students[student_averages < 70]

print("\nStudents averaging below 70:")
print(low_performers)

#below 60
low_grade_count = np.sum(grades < 60)
print("\nNumber of grades below 60:", low_grade_count)

#task 4: rank student performance

print("\n" + "=" * 45)
print("Task 4: rank student performance")
print("=" * 45)

#find the students with the highest average
top_students_index = np.argmax(student_averages)

print("\nTop student:", students[top_students_index])
print("Average:", round(student_averages[top_students_index], 2))

#find the subject with the highest average
best_subject_index = np.argmax(subject_averages)

print("\nBest subject:", subjects[best_subject_index])
print("Average:", round(subject_averages[best_subject_index], 2))

#sort students from lowest to highest average
ranking = np.argsort(student_averages)

print("\nStudent ranking:")
for i in range(len(students)):
  print(
      students[ranking[i]],
      "- Average:",
      round(student_averages[ranking[i]], 2)
  )
#display the top three students
print("\nTop three students:")
for index in ranking[::-1][:3]:
  print(
      students[index],
      "- Average:",
      round(student_averages[index], 2)
  )

  #task 5: improve the dataset
print("\n" + "=" * 45)
print("task 5: Improve the dataset")
print("=" * 45)

updated_grades = grades.copy()
python_index = 1

updated_grades[:, python_index] = np.clip(
    updated_grades[:, python_index] + 5,
    0,
    100
)

print("\nUpdated grades:")
print(updated_grades)

#calculate updated student averages
updated_averages = np.round(
    np.mean(updated_grades, axis=1),
    2
)

print("\nUpdated student averages:")
print(updated_averages)

#determine pass/fail status using an average of 70 or higher
passed = updated_averages >= 70

print("\nPass/fail results:")
for i in range(len(students)):
  if passed[i]:
    status = "PASS"
  else:
    status = "FAIL"

  print(students[i], "-", status)

#final summary report

print("\n" + "=" * 45)
print("Final summary report")
print("=" * 45)

print ("\n{:<12} {:<12} {:<10}".format(
    "Student", "Average", "Status"
))

print("-" * 35)

for i in range(len(students)):
  if passed[i]:
    status = "PASS"
  else:
    status = "FAIL"

  print("{:<12} {:<12.2f} {:<10}".format(
      students[i],
      updated_averages[i],
      status
  ))

print("\nOverall statistics:")
print("Overall average:", round(np.mean(updated_grades), 2))
print("Highest grade:", np.max(updated_grades))
print("Lowest grade:", np.min(updated_grades))
print("Students passing:", np.sum(passed))
print("Students failing:", np.sum(~passed))

print("\nBest performing student after bonus:")
best_updated_index = np.argmax(updated_averages)

print(students[best_updated_index])
print("Average:", updated_averages[best_updated_index])

print("\nAnalysis complete!")

