from array import array
from functools import reduce

students = {}
student_info = {}
subjects = set()
next_id = 1

def announce(func):
  def wrapper(*args, **kwargs):
    result = func(*args, **kwargs)
    if result:
      print("Operation completed")
    return result
  return wrapper

def average_grades(*args):
  if not args:
    return 0
  return sum(args) / len(args)

def create_student(**kwargs):
  return kwargs

@announce
def add_student():
  global next_id
  name = input("Student name: ").strip().title()

  if not name:
    print("Name cannot be empty")
    return False

  if name in students:
    print("Student already exists")
    return False

  students[name] = []
  student_info[next_id] = name
  next_id += 1
  return True

#add a grade
def add_grade():
  name = input("Student name: ").strip().title()

  if name not in students:
    print("Student does not exist")
    return

  subject = input("Subject: ").strip().title()
  if not subject:
    print("Subject cannot be empty")
    return

  try:
    grade = float(input("Grade (0-10): "))
    if not 0 <= grade <= 10:
      print("Grade must be between 0 and 10")
      return
  except ValueError:
    print("Please enter a valid number.")
    return

  students[name].append(grade)
  subjects.add(subject)
  print(f"Added {grade} in {subject} for {name}")

# calculate average using an inner function
def calculate_average(name):
  def get_grades():
    return students.get(name, [])

  grades = get_grades()
  return average_grades(*grades)

#show students and their grades
def show_students():
  if not students:
    print("No students registered.")
    return

  for name, grades in students.items():
    print(f"{name}:")
    print("Grades:", grades if grades else "No grades yet")
    if grades:
      print(f"Average: {calculate_average(name):.2f}")

#find students with average >= 8
def find_top_students():
  top_students = [
      name for name in students
      if students[name]
      and calculate_average(name) >= 8
  ]

  if top_students:
    print("Top students:", ", ".join(top_students))
  else:
    print("No students have an average of 8 or higher.")

#search without worrying about capitalization
def search_student():
  query = input("Search student name: ").strip().lower()

  matches = filter(
      lambda name: query in name.lower(),
      students
  )

  results = list(matches)

  if results:
    for name in results:
      print(name, students[name])
  else:
    print("No matching students found.")

#remove a student
def remove_student():
  name = input("Student name: ").strip().title()

  if name not in students:
    print("Student not found.")
    return

  del students[name]

  #delete students id record
  for sid, info in list(student_info.items()):
    if info == name:
      del student_info[sid]
      break

  print(f"Removed {name}.")

#I wanted to use map(), lambda, array and reduce so this is my excuse
def grade_tools():
  name = input("Student name: ").strip().title()

  if name not in students or not students[name]:
    print("Student not found or has no grades.")
    return

  grades = students[name]

  #array stores value of the same numeric type
  grade_array = array("d", grades)

  #map transforms each grade
  rounded = list(map(lambda x: round(x, 1), grade_array))

  #filter selects passing grades
  passing = list(filter(lambda x: x >= 5, grades))

  #reduce combines values in a total
  total = reduce(lambda a, b: a + b, grades, 0)

  print("Grades", rounded)
  print("Passing grades", passing)
  print("Total", total)
  print(f"Average: {calculate_average(name):.2f}")

#sort students by average grade
def rank_students():
  ranked = [
      name for name in students
      if students[name]
  ]
  ranked.sort(key=lambda name: calculate_average(name), reverse=True)

  if not ranked:
    print("No grades available.")
    return

  for position, name in enumerate(ranked, start=1):
    print(f"{position}. {name}: {calculate_average(name):.2f}")

def countdown(n):
  if n <= 0:
    return
  print(n)
  countdown(n-1)

def main():
  countdown(3)

  while True:
    print("""
===== STUDENT DATA MANAGER =====
1. Add student
2. Add grade
3. Show all students
4. Calculate average
5. Show top students
6. Search student
7. Remove student
8. Show unique subjects
9. Grade tools
10. Rank students
11. Exit
""")

    choice = input("Enter your choice: ").strip()

    if choice == "1":
      add_student()
    elif choice == "2":
      add_grade()
    elif choice == "3":
      show_students()
    elif choice == "4":
      name = input("Student name: ").strip().title()
      if name in students:
        print(f"Average: {calculate_average(name):.2f}")
      else:
        print("Student not found.")
    elif choice == "5":
      find_top_students()
    elif choice == "6":
      search_student()
    elif choice == "7":
      remove_student()
    elif choice == "8":
      print("Subjects:", ", ".join(subjects) if subjects else "None")
    elif choice == "9":
      grade_tools()
    elif choice == "10":
      rank_students()
    elif choice == "11":
      print("Goodbye!")
      break
    else:
      print("Invalid choice, enter a number from 1 to 11.")

if __name__ == "__main__":
  main()

